export function findWorldLanguage(code: string): WorldLanguage {
  const norm = String(code || 'en').trim();
  const exact = WORLD_LANGUAGES.find((l) => l.code.toLowerCase() === norm.toLowerCase());
  if (exact) return exact;
  return {
    code: norm,
    name: norm.toUpperCase(),
    nativeName: norm.toUpperCase(),
    region: 'Global Major',
    dir: RTL_LANGUAGE_CODES.has(norm.toLowerCase()) ? 'rtl' : 'ltr',
  };
}
